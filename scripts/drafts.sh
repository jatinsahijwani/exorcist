#!/usr/bin/env bash
# EXPERIMENTAL. Draft Lean models of our three Rust contracts with NEAR AI, then assess them:
#  1. compile check (inside `exorcist draft`, with a repair loop),
#  2. semantic check: swap each drafted handler into the hand-written network and run the explorer
#     on the same scenarios; the verdicts must match the hand-written models' verdicts,
#  3. a textual diff against the hand-written model, for human review.
# Needs NEARAI_API_KEY. OUT (default drafts/) selects the output directory.
set -euo pipefail
cd "$(dirname "$0")/.."
# optional: NEARAI_API_KEY=... in a local .env (gitignored, never committed)
if [ -f .env ]; then set -a; . ./.env; set +a; fi
export PATH="$HOME/.elan/bin:$PATH"
OUT="${OUT:-drafts}"
E=./.lake/build/bin/exorcist
lake build exorcist >/dev/null
mkdir -p "$OUT"
ok=()
d() { # name file role [feature]
  local f=()
  [ -n "${4:-}" ] && f=(--feature "$4")
  if $E draft --from "$2" --role "$3" --name "$1" --out "$OUT/$1.lean" ${f[@]+"${f[@]}"} ${AI_MODEL:+--ai-model "$AI_MODEL"}; then ok+=("$1"); fi
}
d Token sandbox/contracts/token/src/lib.rs token
d Hook  sandbox/contracts/hook/src/lib.rs hook
d VaultFixed sandbox/contracts/vault/src/lib.rs vault
d VaultGhost sandbox/contracts/vault/src/lib.rs vault ghost_funds_bug
d VaultNoRestore sandbox/contracts/vault/src/lib.rs vault withdraw_no_restore_bug
has() { [[ " ${ok[*]-} " == *" $1 "* ]]; }

# semantic comparison (interpreted #eval, depth 7 to keep it quick)
CMP="$OUT/Compare.lean"
{
  echo "import Verifier.Models.Registry"
  echo "import Verifier.Explore"
  for n in "${ok[@]-}"; do [ -n "$n" ] && echo "import Verifier.Drafts.$n"; done
  cat <<'LEAN'
open NearAsync NearAsync.Vault

/-- A network with some handlers replaced by drafts. -/
def net (tok : Ctx Acct → Call Acct → St Acct → Outcome (St Acct) Acct (Call Acct))
    (vault : Ctx Acct → Call Acct → St Acct → Outcome (St Acct) Acct (Call Acct)) (cfg : Config) (adv : Adversary) :
    System (St Acct) Acct (Call Acct) :=
  { dispatch := fun a => match a with
      | .token => tok | .vault => vault | .hook => hookHandle cfg.hookReturns
      | _ => fun _ _ _ => .panic "no contract",
    canFail := canFail adv }

def verdict (sys : System (St Acct) Acct (Call Acct)) : String :=
  match (explore { sys, init, menu, ok := accounting } 7).trace with
  | some t => s!"violation@{t.length}"
  | none => "clean≤7"

def row (what : String) (hand drafted : System (St Acct) Acct (Call Acct)) : String :=
  let a := verdict hand; let b := verdict drafted
  s!"| {what} | {a} | {b} | {if a == b then "✓ same" else "✗ DIFFERENT"} |"
LEAN
  ve() { # draftName handCfg label
    echo "#eval IO.println (row \"$3\" (system $2 .attackerCode) (net tokenHandle Draft.$1.handle $2 .attackerCode))"
    echo "#eval IO.println (row \"$3 (withdraw adversary)\" (system $2 .nonCallback) (net tokenHandle Draft.$1.handle $2 .nonCallback))"
  }
  has VaultFixed && ve VaultFixed "{}" "vault (fixed build)"
  has VaultGhost && ve VaultGhost "{ depositFixed := false }" "vault (ghost_funds_bug build)"
  has VaultNoRestore && ve VaultNoRestore "{ withdrawFixed := false }" "vault (withdraw_no_restore_bug build)"
  if has Token; then
    echo "#eval IO.println (row \"token, with the vulnerable vault\" (system { depositFixed := false } .attackerCode) (net Draft.Token.handle (vaultHandle { depositFixed := false } .token) { depositFixed := false } .attackerCode))"
    echo "#eval IO.println (row \"token, with the fixed vault\" (system {} .attackerCode) (net Draft.Token.handle (vaultHandle {} .token) {} .attackerCode))"
  fi
} > "$CMP"
# drafts must live under Verifier/Drafts to be importable
mkdir -p Verifier/Drafts
for n in "${ok[@]-}"; do [ -n "$n" ] && cp "$OUT/$n.lean" "Verifier/Drafts/$n.lean"; done
for n in "${ok[@]-}"; do [ -n "$n" ] && lake build "Verifier.Drafts.$n" >/dev/null; done
RES=$(lake env lean "$CMP" 2>&1 || true)
# textual diffs for human review
for n in VaultFixed VaultGhost VaultNoRestore; do
  has "$n" && { git diff --no-index Verifier/Models/Vault.lean "$OUT/$n.lean" > "$OUT/$n.diff" || true; }
done
has Token && { git diff --no-index Verifier/Token.lean "$OUT/Token.lean" > "$OUT/Token.diff" || true; }
has Hook && { git diff --no-index Verifier/Models/Vault.lean "$OUT/Hook.lean" > "$OUT/Hook.diff" || true; }
{
  echo "# Draft assessment (EXPERIMENTAL)"
  echo
  echo "Generated by \`scripts/drafts.sh\` on $(date -u +%Y-%m-%dT%H:%MZ). Drafts compiled: ${ok[*]-none}."
  echo
  echo "Semantic check: each drafted handler replaces the hand-written one in the same network; the bounded"
  echo "explorer (depth 7, scenario of the built-in models) must give the same verdict."
  echo
  echo "| Draft | hand-written model | drafted model | |"
  echo "|---|---|---|---|"
  echo "$RES" | grep '^|' || echo "| (no comparison output) | | | |"
  echo
  echo "Errors from the comparison run, if any:"
  echo '```'
  echo "$RES" | grep -v '^|' | head -40 || true
  echo '```'
  echo
  echo "Textual diffs against the hand-written models: \`$OUT/*.diff\`. A matching verdict on these scenarios"
  echo "is evidence, not proof, that a draft is right; a human still reviews every line."
} > "$OUT/ASSESSMENT.md"
cat "$OUT/ASSESSMENT.md"
